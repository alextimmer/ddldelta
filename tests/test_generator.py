def test_unparsebare_ddl_wirft_generation_error_mit_dateiname(tmp_path):
    delivery = tmp_path / "ddl" / "haynespro" / "2026Q3"
    delivery.mkdir(parents=True)
    (delivery / "kaputt.sql").write_text("PRINT 'kein create table'", encoding="utf-8")
    with pytest.raises(GenerationError, match="kaputt.sql"):
        generate_supplier(config_for(tmp_path), "haynespro")


def test_eigene_policy_schaltet_fuse_ab(tmp_path):
    class AllowEverything:
        def classify(self, change):
            return Severity.SAFE

    config = config_for(tmp_path, policy=AllowEverything())
    old = tmp_path / "ddl" / "haynespro" / "2026Q2"
    new = tmp_path / "ddl" / "haynespro" / "2026Q3"
    old.mkdir(parents=True)
    new.mkdir(parents=True)
    (old / "dbo_WEG.sql").write_text(
        "CREATE TABLE [dbo].[WEG](\n    [id] [int] NOT NULL\n)", encoding="utf-8")
    result = generate_supplier(config, "haynespro")
    content = result.written[0].read_text(encoding="utf-8")
    assert 'DROP TABLE "WEG";' in content
    assert "SELECT 1/0" not in content          # keine Fuse
    assert "-- DROP" not in content             # Statement ausfuehrbar, nicht kommentiert
    assert not [p for p in result.written if "CRITICAL_CHANGES" in p.name]
